CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "desc" TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    type VARCHAR(20) NOT NULL,
    category VARCHAR(100) DEFAULT 'Umum',
    date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    user_id TEXT
);

CREATE TABLE IF NOT EXISTS public.monthly_budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month CHAR(7) NOT NULL,
    category VARCHAR(100) NOT NULL,
    limit_amount NUMERIC NOT NULL CHECK (limit_amount > 0),
    user_id TEXT,
    UNIQUE (user_id, month, category)
);

CREATE TABLE IF NOT EXISTS public.savings_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    target_amount NUMERIC NOT NULL CHECK (target_amount > 0),
    current_amount NUMERIC NOT NULL DEFAULT 0 CHECK (current_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id TEXT
);

CREATE TABLE IF NOT EXISTS public.telegram_processed_updates (
    update_id BIGINT PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id TEXT
);

CREATE TABLE IF NOT EXISTS public.telegram_link_codes (
    code_hash TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.telegram_user_links (
    telegram_user_id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.telegram_webhook_config (
    id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id),
    secret TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.legacy_user_migrations (
    legacy_user_id TEXT PRIMARY KEY,
    email TEXT NOT NULL,
    claimed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS legacy_user_migrations_email_idx
